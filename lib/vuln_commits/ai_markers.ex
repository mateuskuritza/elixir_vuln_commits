defmodule VulnCommits.AiMarkers do
  alias VulnCommits.Text

  @markers ~w(copilot claude chatgpt gpt- cursor codex devin aider gemini ai-generated)

  @repo_files ~w(AGENTS.md CLAUDE.md .cursorrules .cursor/rules
                 .github/copilot-instructions.md GEMINI.md .windsurfrules)

  @attribution ["co-authored-by:", "assisted-by:", "generated with", "generated by"]

  def markers, do: @markers

  def repo_files, do: @repo_files

  def in_message(nil), do: []

  def in_message(message) do
    clean_message = Text.scrub(message)
    lower_message = String.downcase(clean_message)
    lines = String.split(lower_message, "\n")
    attribution_lines = Enum.filter(lines, fn line -> attribution_line?(line) end)
    text = Enum.join(attribution_lines, "\n")

    Enum.filter(@markers, fn marker -> String.contains?(text, marker) end)
  end

  defp attribution_line?(line) do
    Enum.any?(@attribution, fn word -> String.contains?(line, word) end)
  end
end
